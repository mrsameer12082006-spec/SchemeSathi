// Helper function to get translated string
export function getTranslation(lang, key, params = {}) {
  const currentLang = lang === 'hi' ? 'hi' : 'en';
  let str = extraStrings[currentLang]?.[key];
  if (!str) return key;
  Object.keys(params).forEach(p => {
    str = str.replace(`{${p}}`, params[p]);
  });
  return str;
}

